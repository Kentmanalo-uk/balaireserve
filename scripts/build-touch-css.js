/**
 * Balai-Reserve — build public/css/touch.css (run: npm run build:touch-css)
 *
 * 60fps on phones and tablets. Touch screens have no hover, so transitions there only run on state
 * changes (a chip gets selected, a panel opens…). Transitions of colours, borders and box-shadows
 * repaint on the main thread every frame, which drops frames on budget phones; transform and opacity
 * run on the GPU compositor.
 *
 * For every rule in our stylesheets that declares a transition, this writes the same selector (inside
 * the same media query) with only its transform / opacity / visibility parts, keeping their timings, all
 * wrapped in @media (hover: none). Everything else then changes instantly on touch screens. Desktop is
 * untouched. touch.css is loaded after the other stylesheets, so the same selector wins the cascade.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const ROOT = path.join(__dirname, '..');
const CSS_DIR = path.join(ROOT, 'public', 'css');
const SOURCES = ['tokens.css', 'main.css', 'admin-pages.css', 'portal.css', 'booking.css', 'listing.css', 'landing.css', 'auth.css', 'mobile.css'];
const GPU = new Set(['transform', 'opacity', 'visibility', 'translate', 'scale', 'rotate']);

// Split on commas that are not inside parentheses (cubic-bezier(), var(), calc()).
function splitTop(value) {
  const out = []; let depth = 0, cur = '';
  for (const ch of value) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

// One item of the transition shorthand → the GPU-only items it stands for ('all' → transform + opacity).
function gpuItems(item) {
  const words = item.split(/\s+(?![^(]*\))/);
  const propIndex = words.findIndex(w => /^[a-z-]+$/i.test(w) && !/^(ease|ease-in|ease-out|ease-in-out|linear|step-start|step-end|none|infinite)$/i.test(w));
  const prop = propIndex === -1 ? 'all' : words[propIndex].toLowerCase();
  const rest = words.filter((_, i) => i !== propIndex).join(' ');
  if (prop === 'all') return [`transform ${rest}`.trim(), `opacity ${rest}`.trim()];
  return GPU.has(prop) ? [item] : [];
}

function mediaChain(node) {
  const chain = [];
  for (let p = node.parent; p && p.type !== 'root'; p = p.parent) {
    if (p.type === 'atrule' && p.name === 'media') chain.unshift(p.params);
    else if (p.type === 'atrule' && p.name === 'supports') chain.unshift('@supports ' + p.params);
    else if (p.type === 'atrule') return null;   // keyframes etc.
  }
  return chain;
}

const blocks = [];
let rules = 0, dropped = 0;
for (const file of SOURCES) {
  const css = fs.readFileSync(path.join(CSS_DIR, file), 'utf8');
  const tree = postcss.parse(css, { from: file });
  tree.walkRules(rule => {
    const chain = mediaChain(rule);
    if (!chain) return;
    let decl = null;
    rule.each(d => { if (d.type === 'decl' && /^(-webkit-)?transition$/.test(d.prop)) decl = d; });
    if (!decl) return;
    const items = splitTop(decl.value);
    if (items.length === 1 && /^none$/i.test(items[0])) return;
    const keep = items.flatMap(gpuItems);
    if (keep.length === items.length && !items.some(i => /^all\b/i.test(i) || !/\s/.test(i))) return;   // already GPU-only
    rules++;
    if (!keep.length) dropped++;
    blocks.push({ file, chain, selector: rule.selector, value: keep.length ? keep.join(', ') : 'none', important: decl.important });
  });
}

let out = `/* Generated by scripts/build-touch-css.js — do not edit by hand.
   Touch screens: transitions keep only their GPU-composited parts (transform / opacity / visibility), so
   state changes never repaint on the main thread frame by frame. ${rules} rules (${dropped} become instant). */
@media (hover: none) {
`;
let last = '';
for (const b of blocks) {
  if (b.file !== last) { out += `\n/* ${b.file} */\n`; last = b.file; }
  const decl = `transition: ${b.value}${b.important ? ' !important' : ''};`;
  let rule = `${b.selector} { ${decl} }`;
  for (let i = b.chain.length - 1; i >= 0; i--) {
    const c = b.chain[i];
    rule = c.startsWith('@supports ') ? `@supports ${c.slice(10)} { ${rule} }` : `@media ${c} { ${rule} }`;
  }
  out += rule + '\n';
}
out += '}\n';
fs.writeFileSync(path.join(CSS_DIR, 'touch.css'), out);
console.log(`touch.css: ${rules} transition rules rewritten for touch screens (${dropped} become instant), ${(out.length / 1024).toFixed(1)} KB`);
